export function translate(
  language: Language,
  key: string,
  values: Record<string, string> = {},
) {
  const template = language === "en" ? (english[key] ?? key) : key;
  return template.replace(
    /\{(\w+)\}/g,
    (_, name: string) => values[name] ?? `{${name}}`,
  );
}

